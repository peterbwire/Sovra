import assert from 'node:assert/strict';
import { mkdtemp, mkdir, copyFile, chmod, readFile, writeFile, rm } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { buildDeveloperTools } from './build-developer-tools.mjs';
import { requireNode } from '../toolchain/developer-tools/launch.mjs';
import { testInstalledDeveloperTools } from './test-installed-developer-tools.mjs';

const root = resolve('.');
const scratch = await mkdtemp(join(tmpdir(), 'sovra-dev-tools-'));
try {
    requireNode('22.0.0'); assert.throws(() => requireNode('21.9.9'), /22 or newer/);
    const prefix = join(scratch, 'installed Sovra with spaces');
    const tools = join(prefix, 'developer-tools');
    await buildDeveloperTools(tools, process.env.SOVRA_TEST_VSIX);
    await assert.rejects(buildDeveloperTools(tools), /already exists/);
    await mkdir(join(prefix, 'bin'));
    const executable = process.platform === 'win32' ? 'svr.exe' : 'svr';
    await copyFile(join(root, 'target/debug', executable), join(prefix, 'bin', executable));
    await chmod(join(prefix, 'bin', executable), 0o700);
    const launcher = join(tools, 'launch.mjs');
    const run = args => spawnSync(process.execPath, [launcher, ...args], { cwd: scratch, encoding: 'utf8', timeout: 20000, maxBuffer: 2 * 1024 * 1024 });
    const ready = run(['--check']);
    assert.equal(ready.status, 0, ready.stderr); assert.equal(JSON.parse(ready.stdout).success, true);
    const lsp = spawnSync(process.execPath, [join(root, 'scripts/test-lsp.mjs')], { cwd: scratch, env: { ...process.env, SOVRA_LSP_LAUNCHER: launcher }, encoding: 'utf8', timeout: 60000, maxBuffer: 2 * 1024 * 1024 });
    assert.equal(lsp.status, 0, lsp.stdout + lsp.stderr);
    const packages = spawnSync(process.execPath, [join(root, 'scripts/test-lsp-packages.mjs')], { cwd: scratch, env: { ...process.env, SOVRA_LSP_LAUNCHER: launcher }, encoding: 'utf8', timeout: 60000, maxBuffer: 2 * 1024 * 1024 });
    assert.equal(packages.status, 0, packages.stdout + packages.stderr);
    const navigation = spawnSync(process.execPath, [join(root, 'scripts/test-lsp-navigation.mjs')], { cwd: scratch, env: { ...process.env, SOVRA_LSP_LAUNCHER: launcher }, encoding: 'utf8', timeout: 60000, maxBuffer: 2 * 1024 * 1024 });
    assert.equal(navigation.status, 0, navigation.stdout + navigation.stderr);
    const tasks = spawnSync(process.execPath, [join(root, 'scripts/test-task-targets.mjs')], { cwd: scratch, encoding: 'utf8', timeout: 20000, maxBuffer: 2 * 1024 * 1024 });
    assert.equal(tasks.status, 0, tasks.stdout + tasks.stderr);
    await testInstalledDeveloperTools(prefix);
    assert.equal(run(['untrusted-project.js']).status, 1);
    const manifestPath = join(tools, 'manifest.json');
    const manifest = JSON.parse(await readFile(manifestPath, 'utf8'));
    await writeFile(manifestPath, JSON.stringify({ ...manifest, compiler_version: '999.0.0' }));
    const mismatch = run(['--check']);
    assert.equal(mismatch.status, 1); assert.match(mismatch.stderr, /version differ/);
    await writeFile(manifestPath, JSON.stringify(manifest));
    await rm(join(prefix, 'bin', executable));
    assert.match(run(['--check']).stderr, /compiler is missing/);
    const invalid = join(scratch, 'bad.vsix'); await writeFile(invalid, 'not an archive');
    const badOutput = join(scratch, 'bad-output');
    await assert.rejects(buildDeveloperTools(badOutput, invalid), /VSIX/);
    await assert.rejects(readFile(join(badOutput, 'manifest.json')), { code: 'ENOENT' });
    console.log('Developer-tools relocation: installed version check, Node boundary, full stdio LSP from unrelated cwd/spaced path, mismatch/missing compiler, output refusal and invalid VSIX passed.');
} finally { await rm(scratch, { recursive: true, force: true }); }
