import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, readFile } from 'node:fs/promises';
import { startEditor } from '../toolchain/editor/server.mjs';

const { chromium } = createRequire(import.meta.url)('playwright');
const editor = await startEditor();
let browser;
try {
    browser = await chromium.launch({ executablePath: process.env.SOVRA_BROWSER_EXECUTABLE, headless: true, args: ['--no-sandbox'] });
    const page = await browser.newPage({ viewport: { width: 1360, height: 900 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto(editor.url);
    const source = page.getByRole('textbox', { name: 'Sovra source code' });
    await source.fill('fn main() { print("Hello, editor! λ😀") }');
    await page.getByRole('button', { name: 'Check', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Completed successfully' }).waitFor();
    assert.match(await page.locator('#output').textContent(), /No compiler errors/);
    await page.getByRole('button', { name: '▶ Run', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Completed successfully' }).waitFor();
    assert.match(await page.locator('#output').textContent(), /Hello, editor! λ😀/);
    await mkdir('target/editor', { recursive: true });
    await page.screenshot({ path: 'target/editor/desktop.png', fullPage: true });
    await source.fill('fn main() { print("λ😀"); print(missing) }');
    await page.getByRole('button', { name: 'Check', exact: true }).click();
    await page.locator('#diagnostics button').first().waitFor();
    await page.locator('#diagnostics button').first().click();
    assert.equal(await source.evaluate(node => node.value.slice(node.selectionStart, node.selectionEnd)), 'missing');
    await source.fill('fn main() { print("<img src=x onerror=alert(1)>") }');
    await page.getByRole('button', { name: '▶ Run', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Completed successfully' }).waitFor();
    assert.equal(await page.locator('img').count(), 0);
    assert.match(await page.locator('#output').textContent(), /<img/);
    await page.reload();
    assert.match(await source.inputValue(), /onerror/);
    const downloadPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Download source' }).click();
    assert.equal((await downloadPromise).suggestedFilename(), 'main.svr');
    await page.locator('#file').setInputFiles({ name: 'opened.svr', mimeType: 'text/plain', buffer: Buffer.from('fn main() { print("Opened file") }') });
    await page.locator('#filename').filter({ hasText: 'opened.svr' }).waitFor();
    assert.match(await source.inputValue(), /Opened file/);
    await page.getByRole('textbox', { name: 'New source file' }).fill('second.svr');
    await page.getByRole('button', { name: 'Add', exact: true }).click();
    await source.fill('fn main() { print("Second file λ😀") }');
    await page.getByRole('button', { name: '▶ Run', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Completed successfully' }).waitFor();
    assert.match(await page.locator('#output').textContent(), /Second file λ😀/);
    await source.evaluate(node => node.setSelectionRange(3, 7));
    await page.getByRole('button', { name: '◇ opened.svr', exact: true }).click();
    assert.match(await source.inputValue(), /Opened file/);
    await page.getByRole('button', { name: '◇ second.svr', exact: true }).click();
    assert.match(await source.inputValue(), /Second file λ😀/);
    assert.deepEqual(await source.evaluate(node => [node.selectionStart, node.selectionEnd]), [3, 7]);
    await page.reload();
    assert.match(await source.inputValue(), /Second file λ😀/);
    assert.equal(await page.locator('#documents button').count(), 3);
    const exportedPromise = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Export workspace', exact: true }).click();
    const exported = await exportedPromise;
    const workspaceBytes = await readFile(await exported.path());
    const savedWorkspace = JSON.parse(workspaceBytes);
    assert.equal(savedWorkspace.active, 'second.svr');
    assert.equal(savedWorkspace.files.length, 3);
    await page.locator('#workspace-file').setInputFiles({ name: 'bad.json', mimeType: 'application/json', buffer: Buffer.from(JSON.stringify({ ...savedWorkspace, files: [{ name: '../escape.svr', source: '' }] })) });
    await page.getByRole('status').filter({ hasText: 'Cannot import workspace' }).waitFor();
    assert.match(await source.inputValue(), /Second file λ😀/);
    await source.fill('unsaved edit after export');
    await page.locator('#workspace-file').setInputFiles({ name: 'workspace.json', mimeType: 'application/json', buffer: workspaceBytes });
    await page.waitForFunction(() => document.getElementById('source').value.includes('Second file λ😀'));
    assert.match(await source.inputValue(), /Second file λ😀/);
    assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('sovra.editor.workspace')).id), savedWorkspace.id);
    await page.screenshot({ path: 'target/editor/workspace.png', fullPage: true });
    await source.fill('fn main() { while true {} }');
    await page.getByRole('button', { name: '▶ Run', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Compiler working' }).waitFor();
    await page.waitForTimeout(100);
    await page.getByRole('button', { name: 'Stop', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Stopped or failed' }).waitFor();
    await page.getByRole('button', { name: '▶ Run', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Compiler working' }).waitFor();
    await page.getByRole('button', { name: '◇ opened.svr', exact: true }).click();
    await page.getByRole('button', { name: 'Stop', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Source changed · result discarded' }).waitFor();
    assert.match(await source.inputValue(), /Opened file/);
    await source.fill('fn main() { print("Hello, Sovra!") }');
    await page.getByRole('button', { name: '▶ Run', exact: true }).click();
    await page.getByRole('status').filter({ hasText: 'Completed successfully' }).waitFor();
    await page.setViewportSize({ width: 390, height: 844 });
    assert.equal(await page.getByRole('button', { name: 'Open .svr', exact: true }).isVisible(), true);
    assert.equal(await page.getByText('Execution permissions', { exact: true }).isVisible(), true);
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await page.screenshot({ path: 'target/editor/narrow.png', fullPage: true });
    assert.deepEqual(errors, []);
    console.log('Editor Chromium: check/run, Unicode diagnostics, literal output, persistence, open/download, multi-file switching, workspace import/export and rejection, Stop, narrow layout passed.');
} finally { await browser?.close(); await editor.close(); }
