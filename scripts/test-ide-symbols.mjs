import assert from 'node:assert/strict';
import { mkdtemp, writeFile, rm } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';

const directory = await mkdtemp(join(tmpdir(), 'sovra-symbols-'));
const compiler = resolve('target/debug', process.platform === 'win32' ? 'svr.exe' : 'svr');
const path = join(directory, 'main.svr');
const command = args => {
    const result = spawnSync(compiler, args, { encoding: 'utf8', timeout: 20000, maxBuffer: 2 * 1024 * 1024 });
    if (result.error) throw result.error;
    return result;
};
try {
    const source = '// λ😀\nfn root(value: Int) -> Int { return value }\nmod helpers { fn private() {} export fn public() { helpers::private() } }\nfn main() { print("root(1)"); print(root(2)); helpers::public() }';
    await writeFile(path, source);
    const plain = JSON.parse(command(['check', '--format', 'json', path]).stdout);
    assert.equal(plain.symbols, undefined);
    const checked = command(['check', '--format', 'json', '--symbols', path]);
    assert.equal(checked.status, 0, checked.stderr);
    const report = JSON.parse(checked.stdout);
    assert.equal(report.symbols.truncated, false);
    const { declarations, references } = report.symbols;
    assert.deepEqual(declarations.map(value => value.name), ['root', 'main', 'helpers::private', 'helpers::public']);
    const bytes = Buffer.from(source);
    for (const item of declarations) assert.equal(bytes.subarray(item.name_start, item.name_end).toString(), item.name.split('::').at(-1));
    const roots = references.filter(value => value.definition === 0);
    assert.equal(roots.length, 1); // Never infer calls from comment/string spelling.
    assert.equal(bytes.subarray(roots[0].start, roots[0].end).toString(), 'root');
    assert.ok(references.some(value => value.signature?.includes('std::print')));
    const scoped = 'fn pick(value: Int) -> Int { let mut x: Int = value; if true { let x = x + 1; print(x); } else { let x = 2; print(x); } while false { let x = x + 2; print(x); } x = x + 1; let x = x + 2; return x; }';
    await writeFile(path, scoped);
    const scopedResult = command(['check', '--format', 'json', '--symbols', path]);
    assert.equal(scopedResult.status, 0, scopedResult.stdout);
    const local = JSON.parse(scopedResult.stdout).symbols;
    assert.deepEqual(local.locals.map(item => item.kind), ['parameter', 'local', 'local', 'local', 'local', 'local']);
    const targetAt = (fragment, skip = 0) => {
        const offset = Buffer.byteLength(scoped.slice(0, scoped.indexOf(fragment) + skip));
        return local.local_references.find(item => item.start === offset)?.definition;
    };
    assert.equal(targetAt('value;'), 0);
    assert.equal(targetAt('x + 1; print'), 1);
    assert.equal(targetAt('print(x);'), undefined);
    // print(x) points at the call, so inspect its argument separately.
    assert.equal(targetAt('print(x);', 6), 2);
    assert.equal(targetAt('let x = x + 2; print', 8), 1);
    assert.equal(targetAt('} x = x + 1;', 2), 1);
    assert.equal(targetAt('let x = x + 2; return', 8), 1);
    assert.equal(targetAt('return x;', 7), 5);
    assert.match(local.locals[1].signature, /let mut x: Int/);
    assert.equal(local.locals[2].signature, 'let x: Int (inferred)');
    assert.equal(local.locals[2].inferred_type, 'Int');
    const namespaces = 'fn x() -> Int { return 1; } fn main() { let x = 2; print(x); print(x()); }';
    await writeFile(path, namespaces);
    const both = JSON.parse(command(['check', '--format', 'json', '--symbols', path]).stdout).symbols;
    assert.equal(both.local_references.length, 1);
    assert.equal(both.references.filter(item => item.definition === 0).length, 1);
    const aggregates = 'struct Box { value: Int } fn first(value: Int) -> Int { return value } fn second(value: Int) -> Int { return value } fn main() { let value = 1; let box = Box { value: value }; let mut values = [value]; values[0] = value; print(box.value); print(values[0]); }';
    await writeFile(path, aggregates);
    const aggregateResult = command(['check', '--format', 'json', '--symbols', path]);
    assert.equal(aggregateResult.status, 0, aggregateResult.stdout);
    const aggregateSymbols = JSON.parse(aggregateResult.stdout).symbols;
    assert.equal(aggregateSymbols.local_references.filter(item => item.definition === 0).length, 1);
    assert.equal(aggregateSymbols.local_references.filter(item => item.definition === 1).length, 1);
    const fieldName = aggregates.indexOf('box.value') + 4;
    assert.equal(aggregateSymbols.local_references.some(item => item.start === fieldName), false);
    assert.ok(aggregateSymbols.local_references.some(item => item.definition === 4));
    await writeFile(path, 'mod m { fn private() {} } fn main() { m::private() }');
    const invalid = JSON.parse(command(['check', '--format', 'json', '--symbols', path]).stdout);
    assert.equal(invalid.success, false);
    assert.equal(invalid.symbols, undefined);
    assert.equal(command(['check', '--symbols', path]).status, 2);
    assert.equal(command(['check', '--symbols', '--symbols', '--format', 'json', path]).status, 2);
    assert.equal(command(['check', '--symbols', '--format', 'json', directory]).status, 2);
    const inferredSource = '// λ😀\r\ntype Real = Float; struct Point { x: Real }\r\nfn half(v: Real) -> Real { return v; }\r\nfn main() { let number = 1; let word = "λ😀"; let decimal = half(1); let point = Point { x: 2 }; let nested = [[1], [2]]; let empty = []; let holes = [[], []]; let annotated: Real = 1; if true { let number = "inner"; print(number); } print(number); }';
    await writeFile(path, inferredSource);
    const inferredResult = command(['check', '--format', 'json', '--symbols', path]);
    assert.equal(inferredResult.status, 0, inferredResult.stdout + inferredResult.stderr);
    const inferred = JSON.parse(inferredResult.stdout).symbols;
    const byName = name => inferred.locals.find(item => item.name === name);
    for (const [name, type] of [['number', 'Int'], ['word', 'String'], ['decimal', 'Float'], ['point', 'Point'], ['nested', 'Array<Array<Int>>']]) {
        assert.equal(byName(name).inferred_type, type);
        assert.equal(byName(name).signature, `let ${name}: ${type} (inferred)`);
    }
    assert.equal(inferred.locals.filter(item => item.name === 'number')[1].inferred_type, 'String');
    for (const name of ['empty', 'holes']) {
        assert.equal(byName(name).inferred_type, null);
        assert.match(byName(name).signature, /inferred type unavailable/);
    }
    assert.equal(byName('annotated').inferred_type, undefined);
    assert.equal(byName('annotated').signature, 'let annotated: Real');
    // Omitted shadowing declarations must never redirect to the outer binding.
    const longType = 'Alias' + 'A'.repeat(5000);
    const omittedSource = `type ${longType} = Int; fn main() { let x = 1; if true { let x: ${longType} = 2; print(x); } print(x); }`;
    await writeFile(path, omittedSource);
    const omittedResult = command(['check', '--format', 'json', '--symbols', path]);
    assert.equal(omittedResult.status, 0, omittedResult.stdout);
    const omitted = JSON.parse(omittedResult.stdout).symbols;
    assert.equal(omitted.truncated, true);
    assert.equal(omitted.locals.length, 1);
    assert.equal(omitted.local_references.length, 1);
    assert.equal(omitted.local_references[0].start, omittedSource.lastIndexOf('print(x)') + 6);
    assert.equal(omitted.local_references[0].definition, 0);
    const recordSource = `struct ${longType} { x: Int } fn main() { let p = ${longType} { x: 1 }; }`;
    await writeFile(path, recordSource);
    const recordResult = command(['check', '--format', 'json', '--symbols', path]);
    assert.equal(recordResult.status, 0, recordResult.stdout);
    const record = JSON.parse(recordResult.stdout).symbols;
    assert.equal(record.truncated, true);
    assert.equal(record.locals[0].inferred_type, null); // Display allowance, not a fabricated partial type.
    const unavailableSource = `fn main() { ${Array.from({ length: 900 }, (_, index) => `let v${index}_${'a'.repeat(600)} = 1;`).join('')} }`;
    await writeFile(path, unavailableSource);
    assert.equal(command(['check', '--format', 'json', path]).status, 0);
    const unavailableResult = command(['check', '--format', 'json', '--symbols', path]);
    assert.equal(unavailableResult.status, 0, unavailableResult.stdout);
    const unavailable = JSON.parse(unavailableResult.stdout);
    assert.equal(unavailable.success, true);
    assert.equal(unavailable.symbols.unavailable, true);
    assert.equal(unavailable.symbols.truncated, true);
    for (const table of ['declarations', 'references', 'locals', 'local_references']) assert.deepEqual(unavailable.symbols[table], []);
    const many = Array.from({ length: 10000 }, () => 'root(2);').join('');
    await writeFile(path, `fn root(x: Int) {} fn main() { ${many} }`);
    const limited = command(['check', '--format', 'json', '--symbols', path]);
    assert.equal(limited.status, 0, limited.stderr);
    assert.equal(JSON.parse(limited.stdout).symbols.truncated, true);
    assert.ok(Buffer.byteLength(limited.stdout) < 530000);
    const wide = Array.from({ length: 200 }, (_, index) => `fn f${index} // ${'x'.repeat(3300)}\n () {}`).join('\n');
    await writeFile(path, wide);
    const byteLimited = command(['check', '--format', 'json', '--symbols', path]);
    assert.equal(byteLimited.status, 0, byteLimited.stderr);
    assert.equal(JSON.parse(byteLimited.stdout).symbols.truncated, true);
    assert.ok(Buffer.byteLength(byteLimited.stdout) > 480000 && Buffer.byteLength(byteLimited.stdout) < 530000);
    await writeFile(path, `fn main() { ${Array.from({ length: 5000 }, (_, index) => `let v${index} = 1;`).join('')} }`);
    const localLimited = command(['check', '--format', 'json', '--symbols', path]);
    assert.equal(localLimited.status, 0, localLimited.stdout);
    const localLimitedReport = JSON.parse(localLimited.stdout);
    assert.equal(localLimitedReport.symbols.truncated, true);
    assert.ok(localLimitedReport.symbols.locals.length > 0 && localLimitedReport.symbols.locals.length < 5000);
    for (const item of localLimitedReport.symbols.local_references) assert.ok(item.definition < localLimitedReport.symbols.locals.length);
    assert.ok(Buffer.byteLength(localLimited.stdout) < 530000);
    console.log('Compiler symbol evidence: opt-in compatibility, signatures, exact Unicode byte ranges, visibility, calls vs strings, flags and metadata budget passed.');
    const arrays = 'fn size(items: [[Int]]) -> Int { let copied: [[Int]] = items; return std::array_len(copied); }';
    await writeFile(path, arrays);
    const arraysResult = command(['check', '--format', 'json', '--symbols', path]);
    assert.equal(arraysResult.status, 0, arraysResult.stdout + arraysResult.stderr);
    const arraySymbols = JSON.parse(arraysResult.stdout).symbols;
    assert.equal(arraySymbols.truncated, false);
    assert.ok(arraySymbols.locals.some(item => item.signature.includes('items: [[Int]]')));
    assert.ok(arraySymbols.locals.some(item => item.signature.includes('copied: [[Int]]')));
    const { decodeEvidence } = await import('../toolchain/ide/language-server/symbols.mjs');
    assert.equal(decodeEvidence(arraySymbols, Buffer.from(arrays)).locals.length, 2);
} finally { await rm(directory, { recursive: true, force: true }); }
